        /// <summary>取一件物品的悬停标签常量；没有标签返回空数组（不返回 null）。</summary>
        public static string[] Of(string id)
        {
            if (map == null)
            {
                Dictionary<string, string[]> built = new Dictionary<string, string[]>(EntryCount, StringComparer.Ordinal);
                for (int i = 0; i < Pairs.GetLength(0); i++)
                {
                    string[] tags = Pairs[i, 1].Split(',');
                    for (int j = 0; j < tags.Length; j++)
                    {
                        tags[j] = tags[j].Trim();
                    }
                    built[Pairs[i, 0]] = tags;
                }
                map = built;
            }

            string[] hit;
            if (!string.IsNullOrEmpty(id) && map.TryGetValue(id, out hit))
            {
                return hit;
            }
            return Empty;
        }

