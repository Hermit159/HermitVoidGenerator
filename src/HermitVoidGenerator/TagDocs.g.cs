        private static Dictionary<string, string> map;

        private static void Build()
        {
            Dictionary<string, string> built = new Dictionary<string, string>(Pairs.GetLength(0));
            for (int i = 0; i < Pairs.GetLength(0); i++)
            {
                built[Pairs[i, 0]] = Pairs[i, 1];
            }
            map = built;
        }

        /// <summary>取这条词条的说明；没有登记就返回空串。</summary>
        public static string Of(string tag)
        {
            if (string.IsNullOrEmpty(tag)) return "";
            if (map == null) Build();
            string text;
            return map.TryGetValue(tag, out text) ? text : "";
        }
